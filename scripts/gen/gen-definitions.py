"""Copy the definitions the binaries are built with to where they are embedded.

The operator and the director compare the resource definitions they were BUILT
with against the ones a cluster SERVES (internal/schemacheck): a cluster whose
definitions are older prunes every field it does not know, in silence. For that
comparison the binary has to carry its own definitions, and they have to be the
ones in this repository and not a list somebody keeps in step by hand. So they
are copied, whole and unedited:

    charts/gentian-os/crds/gentianos.io_*.yaml  ->  internal/schemacheck/definitions/crds/
    crossplane/xrds/*.yaml                      ->  internal/schemacheck/definitions/xrds/

A field added to a CRD or an XRD is therefore checked from the next build on,
with nothing else to edit.

It also writes the one thing that follows from the SET of definitions rather
than from their fields: the operator reads each definition by name, and its
permission to do so names exactly those and no others. That list is the
+kubebuilder:rbac marker in internal/schemacheck/crdcheck/zz_generated_rbac.go,
which controller-gen then turns into the chart's ClusterRole.

Usage:
    python3 scripts/gen/gen-definitions.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

ROOT = Path(__file__).resolve().parents[2]
CRDS = ROOT / "charts" / "gentian-os" / "crds"
XRDS = ROOT / "crossplane" / "xrds"
EMBED = ROOT / "internal" / "schemacheck" / "definitions"
MARKER = ROOT / "internal" / "schemacheck" / "crdcheck" / "zz_generated_rbac.go"

HEADER = """/*
Copyright The Gentian OS Authors.

This Source Code Form is subject to the terms of the Mozilla Public
License, v. 2.0. If a copy of the MPL was not distributed with this
file, You can obtain one at https://mozilla.org/MPL/2.0/.

SPDX-License-Identifier: MPL-2.0
*/

// Code generated by scripts/gen/gen-definitions.py. DO NOT EDIT.

package crdcheck

// The operator reads the definitions it was built with, each by its name, to
// see whether the cluster serves every field of them. Read, one object at a
// time, of these and of nothing else: no list and no watch, which a rule
// naming resources cannot restrict, and no other CustomResourceDefinition.
//
// The names are every CRD in charts/gentian-os/crds and, for every XRD in
// crossplane/xrds, the composite and the claim CRD Crossplane generates from
// it. Run `make manifests` after adding a definition.
//
// The marker is a free-floating block: controller-gen ignores a block that is
// part of a declaration's doc comment.
//
"""


def sync(sources: list[Path], target: Path) -> None:
    """Make target hold exactly these files, byte for byte."""
    target.mkdir(parents=True, exist_ok=True)
    wanted = {src.name for src in sources}
    for stale in target.iterdir():
        if stale.name not in wanted:
            stale.unlink()
    for src in sources:
        dst = target / src.name
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            shutil.copyfile(src, dst)


def crd_names(files: list[Path]) -> list[str]:
    names = []
    for f in files:
        for doc in yaml.safe_load_all(f.read_text()):
            if doc and doc.get("kind") == "CustomResourceDefinition":
                names.append(doc["metadata"]["name"])
    return names


def xrd_names(files: list[Path]) -> list[str]:
    """The CRDs Crossplane generates: the composite, and the claim if any."""
    names = []
    for f in files:
        for doc in yaml.safe_load_all(f.read_text()):
            if not doc or doc.get("kind") != "CompositeResourceDefinition":
                continue
            names.append(doc["metadata"]["name"])
            claim = (doc["spec"].get("claimNames") or {}).get("plural")
            if claim:
                names.append(f"{claim}.{doc['spec']['group']}")
    return names


def main() -> int:
    crds = sorted(CRDS.glob("gentianos.io_*.yaml"))
    xrds = sorted(XRDS.glob("*.yaml"))
    if not crds or not xrds:
        print("error: no CRDs or no XRDs found — run from a complete checkout, "
              "after controller-gen has written the chart's crds/", file=sys.stderr)
        return 1

    sync(crds, EMBED / "crds")
    sync(xrds, EMBED / "xrds")

    names = sorted(set(crd_names(crds) + xrd_names(xrds)))
    marker = ("// +kubebuilder:rbac:groups=apiextensions.k8s.io,"
              "resources=customresourcedefinitions,"
              f"resourceNames={';'.join(names)},verbs=get\n")
    MARKER.parent.mkdir(parents=True, exist_ok=True)
    body = HEADER + marker
    if not MARKER.exists() or MARKER.read_text() != body:
        MARKER.write_text(body)
    print(f"embedded {len(crds)} CRDs and {len(xrds)} XRD files; "
          f"the operator may read {len(names)} definitions by name")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
