#!/usr/bin/env python3
"""Fetch the resource types each pinned Crossplane provider package ships.

Writes crossplane/providers/types/<provider>.yaml: for every provider in
crossplane/providers/providers.yaml, the package it was read from, whether the
package declares the safe-start capability, and every CustomResourceDefinition
in it -- name (<plural>.<group>), kind, singular, scope, and whether Crossplane
turns it into a ManagedResourceDefinition.

That data is what scripts/lint/lint-provider-activation.py judges
crossplane/providers/activation.yaml against: a kind is turned into its plural
by reading it here, never by guessing, and an activation entry that names a
type the pinned package does not ship is an error.

Which CRDs become ManagedResourceDefinitions is Crossplane's rule, not ours
(internal/converter/custom_to_managed.go at the pinned version): every CRD of
a provider package except the kinds ProviderConfig, ClusterProviderConfig,
ProviderConfigUsage and ClusterProviderConfigUsage. Those four stay plain CRDs
and exist whatever the activation policy says.

This reads the packages from the registry with the `crossplane` CLI
(`crossplane xpkg extract`), so it needs network and is not part of
`make gen-all`. Run it when a provider pin in providers.yaml moves:

    make refresh-provider-types

Usage:
    python3 scripts/gen/gen-provider-types.py
"""

import gzip
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

ROOT = Path(__file__).resolve().parents[2]
PROVIDERS = ROOT / "crossplane" / "providers" / "providers.yaml"
OUT_DIR = ROOT / "crossplane" / "providers" / "types"

# Crossplane's own list of the provider kinds that are not managed resources.
NOT_MANAGED = {
    "ProviderConfig",
    "ClusterProviderConfig",
    "ProviderConfigUsage",
    "ClusterProviderConfigUsage",
}

HEADER = """\
# Generated by scripts/gen/gen-provider-types.py -- do not edit.
# Refresh with `make refresh-provider-types` when the pin in providers.yaml moves.
#
# Every CustomResourceDefinition the package ships at the pinned version.
# managed: true  -> Crossplane installs it as a ManagedResourceDefinition; when
#                   the package declares safe-start it becomes a CRD only if an
#                   activation policy names it (crossplane/providers/activation.yaml).
# managed: false -> a provider configuration kind; always a plain CRD.
"""


def providers() -> list[tuple[str, str]]:
    out = []
    for doc in yaml.safe_load_all(PROVIDERS.read_text()):
        if isinstance(doc, dict) and doc.get("kind") == "Provider":
            out.append((doc["metadata"]["name"], doc["spec"]["package"]))
    return out


def extract(package: str) -> list[dict]:
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "package.gz"
        subprocess.run(
            ["crossplane", "xpkg", "extract", package, "-o", str(target)],
            check=True,
        )
        with gzip.open(target, "rt") as fh:
            return [d for d in yaml.safe_load_all(fh) if isinstance(d, dict)]


def safe_start(docs: list[dict]) -> bool:
    for doc in docs:
        if doc.get("kind") == "Provider" and str(doc.get("apiVersion", "")).startswith("meta.pkg.crossplane.io/"):
            caps = (doc.get("spec") or {}).get("capabilities") or []
            # Crossplane matches the capability loosely: "SafeStart" and
            # "safe-start" are the same declaration.
            return any(str(c).replace("-", "").lower() == "safestart" for c in caps)
    raise SystemExit("package carries no meta.pkg.crossplane.io Provider document")


def render(name: str, package: str, docs: list[dict]) -> str:
    rows = []
    for doc in docs:
        if doc.get("kind") != "CustomResourceDefinition":
            continue
        names = doc["spec"]["names"]
        rows.append(
            (
                doc["metadata"]["name"],
                names["kind"],
                names.get("singular", names["kind"].lower()),
                doc["spec"]["scope"],
                names["kind"] not in NOT_MANAGED,
            )
        )
    if not rows:
        raise SystemExit(f"{package}: no CustomResourceDefinition found -- has the package format changed?")
    lines = [HEADER.rstrip("\n")]
    lines.append(f"provider: {name}")
    lines.append(f"package: {package}")
    lines.append(f"safeStart: {'true' if safe_start(docs) else 'false'}")
    lines.append("types:")
    for crd, kind, singular, scope, managed in sorted(rows):
        lines.append(f"  - name: {crd}")
        lines.append(f"    kind: {kind}")
        lines.append(f"    singular: {singular}")
        lines.append(f"    scope: {scope}")
        lines.append(f"    managed: {'true' if managed else 'false'}")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for name, package in providers():
        print(f"reading {package}", file=sys.stderr)
        docs = extract(package)
        target = OUT_DIR / f"{name}.yaml"
        target.write_text(render(name, package, docs))
        wanted.add(target.name)
    # A provider that left providers.yaml leaves no type list behind.
    for stale in OUT_DIR.glob("*.yaml"):
        if stale.name not in wanted:
            stale.unlink()
            print(f"removed {stale.relative_to(ROOT)} (provider no longer installed)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
