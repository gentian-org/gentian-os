def gen_versions() -> pathlib.Path:
    pins = load_yaml_strings(ROOT / "versions.yaml")
    keys: list[str] = []
    for entry in pins.values():
        for key in entry:
            if key not in keys:
                keys.append(key)
    rows = [[code(component)] + [code(entry.get(k, "")) for k in keys] for component, entry in pins.items()]
    body = [
        "## 1. Pins",
        "",
        "Every external component the installer pulls, pinned once for the "
        "release, with each value exactly as `versions.yaml` writes it; "
        "`scripts/lib/versions.sh` reads the same file for the installer.",
        "",
        *table(["Component"] + [code(k) for k in keys], rows),
    ]
    out = REFERENCE / "versions.md"
    write(out, page("operator", "versions.yaml", "Component versions", body))
    return out


