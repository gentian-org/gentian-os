def gen_namespaces() -> pathlib.Path:
    layout = load_yaml_strings(ROOT / "kernel" / "namespaces.yaml")
    body = [
        "The cluster's namespace layout by tier, as `kernel/namespaces.yaml` "
        "declares it: the one list the installer creates from, the operator "
        "selects on and the lints check against.",
        "",
    ]
    for n, (tier, entries) in enumerate(layout.items(), start=1):
        keys: list[str] = []
        for entry in entries:
            for key in entry:
                if key not in keys:
                    keys.append(key)
        rows = [[code(e.get("name", ""))] + [cell(e.get(k, "")) for k in keys if k != "name"] for e in entries]
        headers = ["Name"] + [code(k) for k in keys if k != "name"]
        body += [f"## {n}. {code(tier)}", "", *table(headers, rows), ""]
    out = REFERENCE / "namespaces.md"
    write(out, page("operator, architect", "kernel/namespaces.yaml", "Namespace layout", body))
    return out


