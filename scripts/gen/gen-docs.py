def install_help() -> tuple[dict[str, tuple[str, str]], dict[str, tuple[str, str]]]:
    """Map each flag install.sh documents to (usage form, help text).

    The usage is printed by driver_usage(): the file's header comment, then a
    heredoc of options. Both are read and returned as (heredoc, header); the
    heredoc is the one written as a flag list, so it is looked up first.
    """
    text = (ROOT / "install.sh").read_text(encoding="utf-8")
    lines = text.splitlines()
    help_for: dict[str, tuple[str, str]] = {}
    header: dict[str, tuple[str, str]] = {}

    # The header: lines of the form "#   ./install.sh --flag   what it does",
    # continued by deeply indented comment lines.
    header_end = lines.index("set -euo pipefail")
    current: str | None = None
    for line in lines[:header_end]:
        match = re.match(r"^#   \./install\.sh (--\S+)(.*)$", line)
        if match:
            flag, rest = match.group(1), match.group(2).strip()
            current = flag if flag not in header else None
            if current:
                header[flag] = (flag, rest)
            continue
        cont = re.match(r"^#\s{20,}(\S.*)$", line)
        if cont and current:
            usage, desc = header[current]
            header[current] = (usage, f"{desc} {cont.group(1).strip()}")
            continue
        current = None

    # The heredoc: entries start with two spaces and a dash; continuation
    # lines are indented further.
    start = next(i for i, l in enumerate(lines) if l.strip() == "cat <<'EOF'")
    end = next(i for i in range(start, len(lines)) if lines[i] == "EOF")
    entry: tuple[list[str], str, list[str]] | None = None

    def flush() -> None:
        if entry is None:
            return
        flags, usage, parts = entry
        desc = one_line(" ".join(parts))
        for flag in flags:
            help_for[flag] = (usage, desc)

    for line in lines[start + 1 : end]:
        match = re.match(r"^  (-\S.*?)(?:\s{2,}(\S.*))?$", line)
        if match:
            flush()
            usage = match.group(1).strip()
            flags = [alias.split()[0] for alias in usage.split(", ")]
            entry = (flags, usage, [match.group(2).strip()] if match.group(2) else [])
            continue
        cont = re.match(r"^\s{10,}(\S.*)$", line)
        if cont and entry is not None:
            entry[2].append(cont.group(1).strip())
            continue
        flush()
        entry = None
    flush()
    return help_for, header


def install_flags() -> list[list[str]]:
    """The flags parse_driver_args() accepts, in the order of its case arms."""
    text = (ROOT / "install.sh").read_text(encoding="utf-8")
    body = text[text.index("parse_driver_args() {") :]
    body = body[: body.index("\n        esac")]
    arms = re.findall(r"^\s{12}(-[^)]*)\)(.*?)(?=^\s{12}-[^)]*\)|\Z)", body, re.M | re.S)
    heredoc, header = install_help()
    rows = []
    for arm, code_text in arms:
        aliases = arm.split("|")
        found = next((heredoc[a] for a in aliases if a in heredoc), None) or next(
            (header[a] for a in aliases if a in header), None
        )
        if found:
            usage, desc = found
            if not all(a in usage for a in aliases):
                usage = ", ".join(aliases) + usage[len(usage.split()[0]) :]
            rows.append([code(usage), cell(desc)])
            continue
        variables = []
        for var in re.findall(r"\b([A-Z][A-Z0-9_]+)=", code_text):
            if var not in variables:
                variables.append(var)
        if variables:
            desc = "Sets " + ", ".join(code(v) for v in variables) + "."
        else:
            # A flag that sets nothing says so itself: the message its arm
            # prints, leaving aside the guard every flag with a value has.
            messages = [
                m for m in re.findall(r'(?:warn|error) "([^"]*)"', code_text) if "requires a value" not in m
            ]
            desc = cell(messages[0]) if messages else ""
        rows.append([", ".join(code(a) for a in aliases), desc])
    return rows


def step_headers() -> dict[str, list[dict[str, str]]]:
    """The header fields of each step file, grouped by phase in step order."""
    phases: dict[str, list[dict[str, str]]] = {}
    for path in sorted((ROOT / "scripts" / "steps").glob("*.sh")):
        fields: dict[str, str] = {}
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.startswith("#"):
                if line.strip():
                    break
                continue
            match = re.match(r"^# (step|phase|requires|provides|mutates|pins):\s*(.*)$", line)
            if match:
                fields[match.group(1)] = match.group(2).strip()
        step = fields.get("step", path.stem)
        fields["step"] = step
        phases.setdefault(fields.get("phase", ""), []).append(fields)
    return phases


def gen_install_steps() -> pathlib.Path:
    body = [
        "## 1. Flags",
        "",
        "The options `install.sh` accepts, in the order it parses them, with the "
        "help `install.sh --help` prints for each. A flag the help does not "
        "describe is shown with the variable it sets.",
        "",
        *table(["Flag", "Description"], install_flags()),
        "",
        "## 2. Steps",
        "",
        "The step files under `scripts/steps/`, in the order the installer runs "
        "them, as their header lines declare them: what each provides, which steps "
        "it requires, what it mutates, and which entries of `versions.yaml` it pins.",
        "",
    ]
    letters = "ABCDE"
    for n, (phase, steps) in enumerate(step_headers().items(), start=1):
        letter = steps[0]["step"][0] if steps and steps[0]["step"][0] in letters else ""
        title = f"Phase {letter}: {phase}" if letter else phase
        body += [f"### 2.{n} {title}", ""]
        rows = [
            [
                code(s["step"]),
                cell(s.get("provides", "")),
                " ".join(code(r) for r in s.get("requires", "").split()),
                cell(s.get("mutates", "")),
                " ".join(code(p) for p in s.get("pins", "").split()),
            ]
            for s in steps
        ]
        body += table(["Step", "Provides", "Requires", "Mutates", "Pins"], rows)
        body.append("")
    out = REFERENCE / "install-steps.md"
    write(out, page("operator", "install.sh and scripts/steps/*.sh", "Install flags and steps", body))
    return out


