LLMS_SECTIONS = [
    ("Overview", "overview"),
    ("Guides", "guides"),
    ("Reference", "reference"),
    ("Concepts", "concepts"),
    ("Decisions", "decisions"),
    ("Security", "security"),
    ("Releases", "releases"),
    ("Contributing", "contributing"),
]

# A line that opens something other than a paragraph of prose: one line of it
# (a heading, a rule, a comment, an image) or a block that runs to the next
# blank line (a list, a table, a quote).
_NOT_PROSE_LINE = ("#", "<!--", "![", "---")
_NOT_PROSE_BLOCK = ("|", "- ", "* ", "+ ", ">")
# A paragraph of labels ("**Companion to:** ...", "**Scope:** ...") is metadata.
_LABEL_RE = re.compile(r"^\*\*[^*]+:\*\*")
_MIN_SUMMARY = 20


def title_and_summary(path: pathlib.Path) -> tuple[str, str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    # Skip front matter.
    if lines and lines[0] == "---":
        lines = lines[lines.index("---", 1) + 1 :]
    title = ""
    rest: list[str] = []
    for i, line in enumerate(lines):
        if line.startswith("# "):
            title = line[2:].strip()
            rest = lines[i + 1 :]
            break
    paragraph: list[str] = []
    skipping = False
    in_code = False
    for line in rest:
        text = line.strip()
        if text.startswith(("```", "~~~")):
            in_code = not in_code
            continue
        if in_code:
            continue
        if not text:
            if paragraph:
                break
            skipping = False
            continue
        if skipping:
            continue
        if paragraph:
            paragraph.append(text)
            continue
        if text.startswith(_NOT_PROSE_LINE):
            continue
        if text.startswith(_NOT_PROSE_BLOCK) or re.match(r"^\d+\. ", text) or _LABEL_RE.match(text):
            skipping = True
            continue
        paragraph.append(text)
    prose = " ".join(paragraph)
    prose = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", prose)
    prose = re.sub(r"\*\*([^*]+)\*\*", r"\1", prose)
    prose = re.sub(r"(?<!\w)\*([^*]+)\*(?!\w)", r"\1", prose)
    summary = first_sentence(prose, 200)
    # A one-word sentence ("Yes.") says nothing on its own: take the next.
    while len(summary) < _MIN_SUMMARY and len(summary) < len(prose):
        more = first_sentence(prose[len(summary) :], 200 - len(summary) - 1)
        if not more:
            break
        summary = f"{summary} {more}"
    return title, summary


def gen_llms(generated: list[pathlib.Path]) -> pathlib.Path:
    _, summary = title_and_summary(DOCS / "index.md")
    lines = [
        "# Gentian OS",
        "",
        f"> {summary}",
        "",
        f"<!-- Generated by {SELF} from the pages under docs/. Do not edit; run make gen-docs. -->",
    ]
    for heading, directory in LLMS_SECTIONS:
        pages = sorted(p for p in (DOCS / directory).rglob("*.md") if p.name != "index.md")
        if not pages:
            continue
        lines += ["", f"## {heading}", ""]
        for p in pages:
            title, page_summary = title_and_summary(p)
            rel = p.relative_to(DOCS).as_posix()
            entry = f"- [{title}]({REPO_BLOB}{rel})"
            if page_summary:
                entry += f": {page_summary}"
            lines.append(entry)
    out = DOCS / "llms.txt"
    write(out, "\n".join(lines) + "\n")
    return out


def main() -> int:
    written = [gen_crds()]
    written.append(gen_install_steps())
    written.append(gen_commands_synopsis())
    written.append(gen_versions())
    written.append(gen_namespaces())
    written.append(gen_llms(written))
    for path in written:
        print(path.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main())
