#!/usr/bin/env python3
"""Write the generated reference pages under docs/ from the sources they describe.

Each page is derived from one source in this repository and carries a header
naming it. The sources stay authoritative; the pages exist so a reader of the
documentation finds the same facts without opening the code:

    config/crd/gentianos.io_*.yaml  ->  docs/reference/crds.md
    install.sh, scripts/steps/*.sh  ->  docs/reference/install-steps.md
    scripts/kubectl-gentian         ->  docs/reference/commands-synopsis.md
    versions.yaml                   ->  docs/reference/versions.md
    kernel/namespaces.yaml          ->  docs/reference/namespaces.md
    docs/**/*.md                    ->  docs/llms.txt

The CRD reference is one page: the flattened field tables of every kind
together come to about 1800 rows (ComponentProfile and ProfileBuild are about
500 each), which with the per-kind headers stays under the ~2500 lines at which
the page would be split into one per kind under docs/reference/crds/.

Run by `make gen-docs` (part of gen-all); verify-gen fails when the committed
pages differ from what this writes, or when a page it writes is untracked.
"""

from __future__ import annotations

import pathlib
import re
import sys
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
REFERENCE = DOCS / "reference"
SELF = "scripts/gen/gen-docs.py"
REPO_BLOB = "https://github.com/gentian-org/gentian-os/blob/develop/docs/"

# A sentence ends at ., ! or ? followed by whitespace, unless the token before
# the period is one of these abbreviations.
_ABBREVIATIONS = ("e.g.", "i.e.", "vs.", "etc.", "cf.", "approx.", "no.")


# ---------------------------------------------------------------------------
# Helpers shared by every page
# ---------------------------------------------------------------------------


def one_line(text: str) -> str:
    """Collapse a multi-line description into one line of single spaces."""
    return re.sub(r"\s+", " ", text or "").strip()


def first_sentence(text: str, limit: int) -> str:
    """The first sentence of text, cut at a word boundary before limit."""
    text = one_line(text)
    if not text:
        return ""
    end = len(text)
    for match in re.finditer(r"[.!?](?=\s)", text):
        head = text[: match.end()]
        last = head.rsplit(" ", 1)[-1].lower()
        if last in _ABBREVIATIONS:
            continue
        end = match.end()
        break
    sentence = text[:end].strip()
    if len(sentence) > limit:
        cut = sentence[: limit - 1].rsplit(" ", 1)[0].rstrip(",;:")
        sentence = cut + "…"
    return sentence


def cell(text: str) -> str:
    """Make text safe inside a Markdown table cell.

    A pipe would end the cell, and an angle bracket outside a code span would
    be read as an HTML tag and swallowed by a renderer.
    """
    parts = one_line(text).replace("|", "\\|").split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("<", "\\<")
    return "`".join(parts)


def code(text: str) -> str:
    return f"`{text}`" if text else ""


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return lines


def page(audience: str, source: str, title: str, body: list[str]) -> str:
    head = [
        "---",
        f"audience: {audience}",
        "type: reference",
        "---",
        "",
        f"<!-- Generated by {SELF} from {source}. Do not edit; run make gen-docs. -->",
        "",
        f"# {title}",
        "",
    ]
    return "\n".join(head + body).rstrip("\n") + "\n"


def write(path: pathlib.Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def load_yaml_strings(path: pathlib.Path) -> Any:
    """Load YAML with every scalar as the string written in the file."""
    with path.open(encoding="utf-8") as handle:
        return yaml.load(handle, Loader=yaml.BaseLoader)


# ---------------------------------------------------------------------------
# 1. CRDs
# ---------------------------------------------------------------------------


def schema_type(schema: dict[str, Any]) -> str:
    if schema.get("x-kubernetes-int-or-string"):
        return "int-or-string"
    typ = schema.get("type", "")
    if typ == "array":
        return "[]" + schema_type(schema.get("items", {}) or {})
    if typ == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return "map[string]" + schema_type(extra)
        if schema.get("x-kubernetes-preserve-unknown-fields") and not schema.get("properties"):
            return "object (free-form)"
        return "object"
    if typ == "string" and schema.get("format"):
        return f"string ({schema['format']})"
    if typ == "integer" and schema.get("format"):
        return f"integer ({schema['format']})"
    return typ or "object"


def flatten_fields(schema: dict[str, Any], prefix: str, rows: list[list[str]]) -> None:
    required = set(schema.get("required", []) or [])
    for name, sub in (schema.get("properties", {}) or {}).items():
        if not prefix and name in ("apiVersion", "kind", "metadata"):
            continue
        path = f"{prefix}.{name}" if prefix else name
        rows.append(
            [
                code(path),
                cell(schema_type(sub)),
                "yes" if name in required else "",
                cell(lead_identifier(name, first_sentence(sub.get("description", ""), 160))),
            ]
        )
        descend(sub, path, rows)


def lead_identifier(name: str, sentence: str) -> str:
    """Go doc comments open with the field's name ("Catalogue is ..."); render
    that word as the identifier it is."""
    m = re.match(r"(\w+)(\b.*)", sentence, re.S)
    if m and m.group(1).lower() == name.lower():
        return f"`{m.group(1)}`{m.group(2)}"
    return sentence


def descend(schema: dict[str, Any], path: str, rows: list[list[str]]) -> None:
    typ = schema.get("type", "")
    if typ == "array":
        items = schema.get("items", {}) or {}
        if items.get("type") == "object" and items.get("properties"):
            flatten_fields(items, path + "[]", rows)
        elif items.get("type") == "object" and isinstance(items.get("additionalProperties"), dict):
            descend(items, path + "[]", rows)
    elif typ == "object":
        extra = schema.get("additionalProperties")
        if schema.get("properties"):
            flatten_fields(schema, path, rows)
        elif isinstance(extra, dict) and extra.get("properties"):
            flatten_fields(extra, path + "{}", rows)
        elif isinstance(extra, dict) and extra.get("type") == "array":
            descend(extra, path + "{}", rows)


def load_crds() -> list[dict[str, Any]]:
    crds = []
    for path in sorted((ROOT / "config" / "crd").glob("gentianos.io_*.yaml")):
        with path.open(encoding="utf-8") as handle:
            doc = yaml.safe_load(handle)
        spec = doc["spec"]
        versions = spec["versions"]
        storage = next((v for v in versions if v.get("storage")), versions[0])
        schema = storage.get("schema", {}).get("openAPIV3Schema", {}) or {}
        rows: list[list[str]] = []
        flatten_fields(schema, "", rows)
        crds.append(
            {
                "source": path.relative_to(ROOT).as_posix(),
                "group": spec["group"],
                "kind": spec["names"]["kind"],
                "plural": spec["names"]["plural"],
                "short_names": spec["names"].get("shortNames", []) or [],
                "scope": spec["scope"],
                "versions": [v["name"] for v in versions],
                "description": one_line(schema.get("description", "")),
                "rows": rows,
            }
        )
    crds.sort(key=lambda c: c["kind"])
    return crds


def gen_crds() -> pathlib.Path:
    crds = load_crds()
    body = [
        f"The custom resource definitions of the `{crds[0]['group']}` API group, "
        "with every field of their `spec` and `status`. Paths are dotted from the "
        "object root; `[]` marks the items of a list and `{}` the values of a map. "
        "`apiVersion`, `kind` and `metadata` are the standard object fields and are "
        "not listed.",
        "",
        "| Kind | Scope | Description |",
        "|---|---|---|",
    ]
    for n, crd in enumerate(crds, start=1):
        body.append(
            f"| [{crd['kind']}](#{n}-{crd['kind'].lower()}) | {crd['scope']} | "
            f"{cell(first_sentence(crd['description'], 160))} |"
        )
    body.append("")
    for n, crd in enumerate(crds, start=1):
        body += [
            f"## {n}. {crd['kind']}",
            "",
            *table(
                ["Attribute", "Value"],
                [
                    ["Group", code(crd["group"])],
                    ["Version", ", ".join(code(v) for v in crd["versions"])],
                    ["Scope", crd["scope"]],
                    ["Plural", code(crd["plural"])],
                    ["Short names", ", ".join(code(s) for s in crd["short_names"])],
                ],
            ),
            "",
        ]
        if crd["description"]:
            body += [cell(crd["description"]), ""]
        body += [*table(["Field", "Type", "Required", "Description"], crd["rows"]), ""]
    out = REFERENCE / "crds.md"
    write(
        out,
        page(
            "operator, app-author, architect",
            "config/crd/gentianos.io_*.yaml",
            "Custom resource definitions",
            body,
        ),
    )
    return out


