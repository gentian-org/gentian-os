def gen_commands_synopsis() -> pathlib.Path:
    lines = (ROOT / "scripts" / "kubectl-gentian").read_text(encoding="utf-8").splitlines()
    start = lines.index("# Usage:")
    block: list[str] = []
    for line in lines[start + 1 :]:
        if not line.startswith("#"):
            break
        block.append(line)
    # The synopsis is the indented lines; the prose paragraph that follows the
    # last of them, in the same comment, is not part of it.
    last = max(i for i, l in enumerate(block) if l.startswith("#   "))
    block = block[: last + 1]
    stripped = [re.sub(r"^# ?", "", l) for l in block]
    while stripped and not stripped[0].strip():
        stripped.pop(0)
    body = [
        "The synopsis of every `kubectl gentian` command, as the plugin's own "
        "header states it; the full description of each command is in "
        "[commands.md](commands.md).",
        "",
        "## 1. Synopsis",
        "",
        "```text",
        *stripped,
        "```",
    ]
    out = REFERENCE / "commands-synopsis.md"
    write(out, page("operator", "scripts/kubectl-gentian", "kubectl gentian synopsis", body))
    return out


