#!/usr/bin/env python3
"""Render the Keycloak login theme into the ConfigMap Argo CD applies.

The theme is authored as real files under kernel/services/keycloak-idp/theme/ so
the FreeMarker templates and CSS can be edited, diffed and linted like source.
Keycloak wants them on disk and the delivery mechanism is a ConfigMap volume, so
they have to appear in YAML too. Maintaining both by hand would be two copies of
one thing, which this repository has been bitten by more than once — a validator
reading a renamed field, a CRD citing a deleted document. So the YAML is
generated and `make verify-gen` fails when it drifts.

One flat ConfigMap, expanded into Keycloak's nested layout by an init container.

A ConfigMap key cannot contain "/", so the tree is encoded as "__" and restored at
startup. The alternatives were worse. Per-file subPath mounts, or a per-file
`items` list, both mean every new template also needs a matching entry in the
Helm values — the same duplication one level down. A ConfigMap per directory does
not work at all: login/resources/css would have to mount *inside* the read-only
login volume, which contains no such directory to mount onto.

With the init container, adding a template changes only this file's output.
"""

from __future__ import annotations

import base64
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]   # scripts/gen/ -> repo root
THEME = REPO / "kernel/services/keycloak-idp/theme"
# A single output under templates/, not one copy per environment.
#
# This used to write manifests/dev/ and manifests/prod/ because the kernel
# ApplicationSet synced kernel/services/<app>/<env> and anything at the
# manifests/ root was never applied. The appset-managed services have since been
# converted to Helm charts — manifests/ now holds Chart.yaml, values.yaml and
# templates/ — and the per-env directories were deleted. This script was not
# updated with them, so `make gen-theme` died on a path that no longer exists:
#
#   FileNotFoundError: .../manifests/dev/theme-configmap.yaml
#
# That failed the verify-gen job, which fails the whole CI run, which skips the
# docker job (needs: [go] and friends) — so no operator image was published at
# all. A stale generator output path quietly stopped the entire delivery
# pipeline.
#
# The ConfigMap needs no templating, but it lives in templates/ regardless:
# Helm only renders files from there, and a chart's non-template files are not
# applied.
OUTS = [REPO / "kernel/services/keycloak-idp/manifests/templates/theme-configmap.yaml"]

HEADER = """# GENERATED by scripts/gen/gen-keycloak-theme-configmap.py — do not edit.
#
# Source of truth: kernel/services/keycloak-idp/theme/
# Regenerate with: make gen-theme     (verified by: make verify-gen)
#
# The Gentian login theme. Keys are theme-relative paths with "/" replaced by
# "__", because a ConfigMap key may not contain a slash; the init container in
# the keycloakx values expands them back into /opt/keycloak/themes/gentian.
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: keycloak-idp-theme
  namespace: platform-kernel
  annotations:
    argocd.argoproj.io/sync-wave: "-1"
"""

# Anything not decodable as UTF-8 goes to binaryData. The favicon is the only such
# file today; the kubelet materialises both maps as real files, so the init
# container copies them identically.
BINARY_HEADER = "binaryData:\n"
TEXT_HEADER = "data:\n"


def render() -> tuple[str, int]:
    files = sorted(p for p in THEME.rglob("*") if p.is_file())
    if not files:
        sys.exit(f"no theme files under {THEME}")

    text_out: list[str] = []
    binary_out: list[str] = []
    for path in files:
        rel = str(path.relative_to(THEME))
        if "__" in rel:
            sys.exit(f"{rel}: a literal '__' in a theme path is ambiguous once encoded")
        key = rel.replace("/", "__")
        raw = path.read_bytes()
        try:
            text = raw.decode()
        except UnicodeDecodeError:
            binary_out.append(f"  {key}: {base64.b64encode(raw).decode()}\n")
            continue
        if "\r" in text:
            sys.exit(f"{rel}: CRLF line endings would reach Keycloak verbatim")
        # "|-" rather than "|" so a missing trailing newline in a source file
        # cannot silently change the rendered bytes.
        text_out.append(f"  {key}: |-\n")
        for line in text.rstrip("\n").split("\n"):
            text_out.append(f"    {line}\n" if line else "\n")

    out = [HEADER]
    if text_out:
        out.append(TEXT_HEADER)
        out.extend(text_out)
    if binary_out:
        out.append(BINARY_HEADER)
        out.extend(binary_out)
    return "".join(out), len(files)


def main() -> int:
    rendered, count = render()
    if "--check" in sys.argv:
        stale = [o for o in OUTS if (o.read_text() if o.exists() else "") != rendered]
        if stale:
            for o in stale:
                print(f"{o.relative_to(REPO)} is out of date — run 'make gen-theme'")
            return 1
        print(f"theme ConfigMaps are up to date ({count} theme file(s))")
        return 0
    for o in OUTS:
        o.write_text(rendered)
        print(f"wrote {o.relative_to(REPO)} ({count} theme file(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
