#!/usr/bin/env python3
"""Write the platform's version line from the chart's version.

The chart's version is the platform's number (docs/plans/versioning.md §1.1):
X.Y.0 on the release commit, X.(Y+1).0-dev on the commit after it. The
operator and the director compare profiles' floors and backup bundles with
the LINE of that number, its major and minor, and used to carry it as a
constant kept in step by hand -- which it was not: the chart said 0.4.1 while
the constant said 0.5. This writes the constant from the chart, so the two
cannot disagree.

    charts/gentian-os/Chart.yaml  ->  internal/platformversion/line.go

Run by `make gen-platform-version` (part of gen-all); verify-gen checks the
output is committed.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CHART = ROOT / "charts" / "gentian-os" / "Chart.yaml"
OUT = ROOT / "internal" / "platformversion" / "line.go"

HEADER = """/*
Copyright The Gentian OS Authors.

This Source Code Form is subject to the terms of the Mozilla Public
License, v. 2.0. If a copy of the MPL was not distributed with this
file, You can obtain one at https://mozilla.org/MPL/2.0/.

SPDX-License-Identifier: MPL-2.0
*/

// Code generated by scripts/gen/gen-platform-version.py from charts/gentian-os/Chart.yaml. DO NOT EDIT.

package platformversion

// Line is the version line this platform is built towards: the major and
// minor of the chart's version, %s. It moves with the chart: the release
// commit that cuts X.Y.0 and the commit after it, which sets X.(Y+1).0-dev,
// both change it.
const Line = "%s"

// ChartVersion is the chart's version as written, the platform's number.
const ChartVersion = "%s"
"""


def main() -> int:
    text = CHART.read_text(encoding="utf-8")
    m = re.search(r"^version:\s*[\"']?([^\s\"']+)", text, re.M)
    if not m:
        print(f"{CHART}: no version", file=sys.stderr)
        return 1
    version = m.group(1)
    parts = re.match(r"^v?(\d+)\.(\d+)(?:\.(\d+))?", version)
    if not parts:
        print(f"{CHART}: version {version!r} is not <major>.<minor>[.<patch>]", file=sys.stderr)
        return 1
    line = f"{parts.group(1)}.{parts.group(2)}"
    OUT.write_text(HEADER % (version, line, version), encoding="utf-8")
    print(f"platform version line {line} (chart {version}) -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
