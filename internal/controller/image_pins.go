// What a credential bound to one app can be made to pull.
//
// The registry grants that credential the app's repositories and no others,
// but a token stops at the repository: it says nothing of which build. The
// profile says which (spec.package.images), and this is what holds a pod to
// it: a Kyverno Policy in the component's namespace, which refuses a pod
// naming one of those repositories at any other build, in Enforce and failing
// closed. A pod is the only thing that can use the pull Secret by naming it,
// and a kubelet does not ask who may, so admission is where this is decided.
// It says nothing of any other image, so two apps in a namespace do not
// refuse each other's.

// +kubebuilder:rbac:groups=kyverno.io,resources=policies,verbs=get;list;watch;create;update;patch;delete

var kyvernoPolicyGVK = schema.GroupVersionKind{Group: "kyverno.io", Version: "v1", Kind: "Policy"}

// imagePinsName is the component's Policy.
func imagePinsName(comp *gentianov1alpha1.Component) string { return "image-pins-" + comp.Name }

// imagePinsPolicy is the Policy that holds a component's pods to its pins.
func imagePinsPolicy(comp *gentianov1alpha1.Component, images []gentianov1alpha1.PinnedImage) *unstructured.Unstructured {
	var pinned, allowed []interface{}
	for _, image := range images {
		pinned = append(pinned, image.Repository, image.Repository+":*", image.Repository+"@*")
		allowed = append(allowed, image.Repository+"@"+image.Digest)
	}
	var each []interface{}
	for _, list := range []string{
		"request.object.spec.containers",
		"request.object.spec.initContainers || `[]`",
		"request.object.spec.ephemeralContainers || `[]`",
	} {
		each = append(each, map[string]interface{}{
			"list": list,
			"deny": map[string]interface{}{"conditions": map[string]interface{}{"all": []interface{}{
				map[string]interface{}{"key": "{{ element.image }}", "operator": "AnyIn", "value": pinned},
				map[string]interface{}{"key": "{{ element.image }}", "operator": "AnyNotIn", "value": allowed},
			}}},
		})
	}
	policy := &unstructured.Unstructured{Object: map[string]interface{}{
		"metadata": map[string]interface{}{
			"name":      imagePinsName(comp),
			"namespace": comp.Namespace,
			"annotations": map[string]interface{}{
				// On the pod itself, as a kubelet pulls for a pod: a rule
				// autogenerated for its Deployment would be a second answer.
				"pod-policies.kyverno.io/autogen-controllers": "none",
			},
		},
		"spec": map[string]interface{}{
			"validationFailureAction": "Enforce",
			"failurePolicy":           "Fail",
			"background":              false,
			"rules": []interface{}{map[string]interface{}{
				"name": "pinned-images",
				"match": map[string]interface{}{"any": []interface{}{map[string]interface{}{
					"resources": map[string]interface{}{"kinds": []interface{}{"Pod", "Pod/ephemeralcontainers"}},
				}}},
				"validate": map[string]interface{}{
					"message": "this image is pinned to one build by " + comp.Name + "'s profile (spec.package.images)",
					"foreach": each,
				},
			}},
		},
	}}
	policy.SetGroupVersionKind(kyvernoPolicyGVK)
	return policy
}

// ensureImagePins holds the component's pods to the builds its profile
// names, or takes the Policy away from one that no longer names any. An
// error stops the reconcile: a pinned component does not run unpinned.
func (r *ComponentReconciler) ensureImagePins(ctx context.Context, comp *gentianov1alpha1.Component, profile *gentianov1alpha1.ComponentProfile) error {
	key := types.NamespacedName{Name: imagePinsName(comp), Namespace: comp.Namespace}
	existing := &unstructured.Unstructured{}
	existing.SetGroupVersionKind(kyvernoPolicyGVK)
	if len(profile.Spec.Package.Images) == 0 {
		existing.SetName(key.Name)
		existing.SetNamespace(key.Namespace)
		if err := r.Delete(ctx, existing); err != nil && !errors.IsNotFound(err) && !meta.IsNoMatchError(err) {
			return fmt.Errorf("delete Policy %s: %w", key.Name, err)
		}
		return nil
	}
	desired := imagePinsPolicy(comp, profile.Spec.Package.Images)
	if err := controllerutil.SetControllerReference(comp, desired, r.Scheme); err != nil {
		return err
	}
	err := r.Get(ctx, key, existing)
	if errors.IsNotFound(err) {
		if err := r.Create(ctx, desired); err != nil {
			return fmt.Errorf("create Policy %s: %w", key.Name, err)
		}
		return nil
	}
	if err != nil {
		return err
	}
	if equality.Semantic.DeepEqual(existing.Object["spec"], desired.Object["spec"]) {
		return nil
	}
	existing.Object["spec"] = desired.Object["spec"]
	if err := r.Update(ctx, existing); err != nil {
		return fmt.Errorf("update Policy %s: %w", key.Name, err)
	}
	return nil
}

// platformCredentials are the profiles the platform tenant holds a set
// credential for: a Repository of that tenant bound to the profile, whose
// credential the store has answered for. Another tenant's repository is no
// reason to place anything in the platform tenant.
func (r *TenantReconciler) platformCredentials(ctx context.Context) (map[string]bool, error) {
	tenants := &gentianov1alpha1.TenantList{}
	if err := r.List(ctx, tenants); err != nil {
		return nil, err
	}
	platform := ""
	for i := range tenants.Items {
		t := &tenants.Items[i]
		if t.DeletionTimestamp == nil && tenantAdoptsKernelRealm(t, r.KernelRealm) {
			platform = t.Name
			break
		}
	}
	out := map[string]bool{}
	if platform == "" {
		return out, nil
	}
	list := &unstructured.UnstructuredList{}
	list.SetGroupVersionKind(repositoryClaimGVK.GroupVersion().WithKind(repositoryClaimGVK.Kind + "List"))
	if err := r.List(ctx, list, client.InNamespace(repositoryClaimNamespace)); err != nil {
		if meta.IsNoMatchError(err) {
			return out, nil
		}
		return nil, fmt.Errorf("list repositories: %w", err)
	}
	for i := range list.Items {
		spec, _, _ := unstructured.NestedMap(list.Items[i].Object, "spec")
		owner, _ := spec["tenant"].(string)
		app, _ := spec["app"].(string)
		if owner == platform && app != "" &&
			credentialprobe.Satisfied(ctx, r.Client, "repository-"+list.Items[i].GetName()) {
			out[app] = true
		}
	}
	return out, nil
}
